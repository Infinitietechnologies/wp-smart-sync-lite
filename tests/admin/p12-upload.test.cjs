const test = require('node:test');
const assert = require('node:assert/strict');
const { boot, googleKey, chooseGoogleFile } = require('./harness.cjs');

test('P12 selection shows account fields without reading or exposing binary key material', async t => {
    const app = await boot('wizard', { data: { service_provider: 'google' } }); t.after(() => app.close());
    app.window.FileReader = class { constructor() { throw new Error('P12 must not use JSON FileReader'); } };
    await chooseGoogleFile(app, 'private-binary-fixture', 'service-account.p12');
    assert.match(app.$('#service-json').attr('accept'), /\.p12/);
    assert.equal(app.$('#google-p12-fields').prop('hidden'), false);
    assert.equal(app.$('#google-file-preview').prop('hidden'), true);
    assert.equal(app.$('#google-json-code').text(), '');
    assert.equal(app.$('#google-upload').attr('data-state'), 'ready');
    assert.equal(app.requests.length, 0);
    app.$('#step-1-next').trigger('click');
    assert.equal(app.window.document.activeElement.id, 'google-p12-email');
    app.$('#google-p12-email').val('media@my-project.iam.gserviceaccount.com').trigger('input');
    app.$('#google-p12-project').val('1234567').trigger('input');
    app.$('#step-1-next').trigger('click');
    assert.equal(app.window.document.activeElement.id, 'google-p12-project');
    assert.equal(app.requests.length, 0);
    app.$('#google-p12-project').val('my-project').trigger('input');
    app.$('#google-p12-password').val('custom fixture password').trigger('input');
    app.$('#step-1-next').trigger('click');
    const request = app.latest('list_s3_buckets');
    assert.equal(request.options.data.get('service_json').name, 'service-account.p12');
    assert.equal(request.options.data.get('google_p12_email'), 'media@my-project.iam.gserviceaccount.com');
    assert.equal(request.options.data.get('google_p12_project'), 'my-project');
    assert.equal(request.options.data.get('google_p12_password'), 'custom fixture password');
    assert.equal(app.$('#google-p12-email').prop('disabled'), true);
    request.resolve({ buckets: [{ name: 'test-bucket', region: 'EU' }], selectionToken: 'p12-selection' });
    app.$('[data-setup-step="1"]').trigger('click');
    app.$('#google-p12-project').val('replacement-project').trigger('input');
    assert.equal(app.$('[data-setup-step="2"]').prop('disabled'), true);
    app.$('#step-1-next').trigger('click');
    app.latest('list_s3_buckets').resolve({ buckets: [{ name: 'new-bucket', region: 'EU' }], selectionToken: 'new-p12-selection' });
    app.$('#step-2-next').trigger('click');
    const save = app.latest('configure_aws');
    assert.equal(save.options.data.google_selection_token, 'new-p12-selection');
    assert.equal(save.options.data.google_p12_password, undefined);
    save.resolve();
    assert.equal(app.$('#google-p12-fields').prop('hidden'), true);
    assert.equal(app.$('#google-p12-email').val(), '');
    assert.equal(app.$('#google-p12-password').val(), '');
});

test('P12 removal and replacement with JSON clear P12 metadata and retain the existing JSON preview', async t => {
    const app = await boot('wizard', { data: { service_provider: 'google' } }); t.after(() => app.close());
    await chooseGoogleFile(app, 'binary-fixture', 'service-account.P12');
    app.$('#google-p12-email').val('secret@my-project.iam.gserviceaccount.com');
    app.$('#google-p12-password').val('old-password');
    await chooseGoogleFile(app, googleKey(), 'replacement.json');
    assert.equal(app.$('#google-p12-fields').prop('hidden'), true);
    assert.equal(app.$('#google-p12-email').val(), '');
    assert.equal(app.$('#google-p12-password').val(), '');
    assert.equal(app.$('#google-file-preview').prop('hidden'), false);
    app.$('#step-1-next').trigger('click');
    assert.equal(app.latest('list_s3_buckets').options.data.has('google_p12_password'), false);
});
